def translate_text(text: str) -> str:
    if not text:
        return text
    for pattern, repl in _RULES:
        new_text, count = pattern.subn(repl, text)
        if count:
            return new_text
    return text


def translate_finding(finding: dict) -> dict:
    translated = dict(finding)
    for field in ("title", "description", "recommendation", "category"):
        if translated.get(field):
            translated[field] = translate_text(translated[field])
    return translated
